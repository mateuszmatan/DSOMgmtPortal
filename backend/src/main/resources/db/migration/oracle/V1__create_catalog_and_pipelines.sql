-- DevSecOps management portal schema.
-- Written for Oracle 19c and later; the same script runs on H2 in Oracle mode for local work and tests.

CREATE TABLE DSO_PRODUCT (
    ID                          NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    CODE                        VARCHAR2(50)    NOT NULL,
    NAME                        VARCHAR2(200)   NOT NULL,
    DESCRIPTION                 VARCHAR2(4000),
    OWNER_TEAM                  VARCHAR2(200),
    CONTACT_EMAIL               VARCHAR2(320),
    ASOC_KEY_ID                 VARCHAR2(200)   NOT NULL,
    ASOC_SECRET_CREDENTIALS_ID  VARCHAR2(200),
    CREATED_AT                  TIMESTAMP       NOT NULL,
    UPDATED_AT                  TIMESTAMP       NOT NULL,
    VERSION                     NUMBER(10)      DEFAULT 0 NOT NULL,
    CONSTRAINT PK_DSO_PRODUCT PRIMARY KEY (ID),
    CONSTRAINT UK_DSO_PRODUCT_CODE UNIQUE (CODE),
    CONSTRAINT UK_DSO_PRODUCT_NAME UNIQUE (NAME)
);

CREATE TABLE DSO_SERVICE (
    ID                          NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    PRODUCT_ID                  NUMBER(19)      NOT NULL,
    NAME                        VARCHAR2(100)   NOT NULL,
    DESCRIPTION                 VARCHAR2(2000),
    DISPLAY_ORDER               NUMBER(5)       DEFAULT 0 NOT NULL,
    BUILD_TOOL                  VARCHAR2(20)    NOT NULL,
    DEPLOY_TARGET               VARCHAR2(20)    NOT NULL,
    SOURCE_DIR                  VARCHAR2(500)   DEFAULT '.' NOT NULL,
    JAVA_PATH                   VARCHAR2(500),
    BUILD_TOOL_AUTO_SETUP       NUMBER(1)       DEFAULT 0 NOT NULL,
    APPSCAN_APP_ID              VARCHAR2(36)    NOT NULL,
    SAST_SCAN_NAME              VARCHAR2(200),
    DAST_ENABLED                NUMBER(1)       DEFAULT 0 NOT NULL,
    DAST_TARGET_URL             VARCHAR2(1000),
    DAST_PRESENCE_ID            VARCHAR2(100),
    SONAR_PROJECT_NAME          VARCHAR2(200),
    SONAR_PROJECT_KEY           VARCHAR2(400),
    NEXUS_IQ_APPLICATION        VARCHAR2(200),
    NEXUS_IQ_SCAN_PATTERNS      VARCHAR2(2000),
    REPOSITORY_URL              VARCHAR2(1000),
    BITBUCKET_CREDENTIALS_ID    VARCHAR2(200),
    GOLDEN_FIX_ENABLED          NUMBER(1)       DEFAULT 1 NOT NULL,
    METRICS_ENABLED             NUMBER(1)       DEFAULT 1 NOT NULL,
    INFLUX_PROJECT              VARCHAR2(200)   NOT NULL,
    INFLUX_ENV                  VARCHAR2(50)    DEFAULT 'test' NOT NULL,
    APP_NAME                    VARCHAR2(200),
    ARTIFACT_NAME               VARCHAR2(300),
    ADDITIONAL_CONFIG           CLOB,
    CREATED_AT                  TIMESTAMP       NOT NULL,
    UPDATED_AT                  TIMESTAMP       NOT NULL,
    VERSION                     NUMBER(10)      DEFAULT 0 NOT NULL,
    CONSTRAINT PK_DSO_SERVICE PRIMARY KEY (ID),
    CONSTRAINT FK_DSO_SERVICE_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES DSO_PRODUCT (ID) ON DELETE CASCADE,
    CONSTRAINT UK_DSO_SERVICE_NAME UNIQUE (PRODUCT_ID, NAME),
    CONSTRAINT UK_DSO_SERVICE_INFLUX UNIQUE (INFLUX_PROJECT, INFLUX_ENV),
    CONSTRAINT UK_DSO_SERVICE_SONAR_KEY UNIQUE (SONAR_PROJECT_KEY),
    CONSTRAINT CK_DSO_SERVICE_BUILD_TOOL CHECK (BUILD_TOOL IN ('GRADLE', 'MAVEN', 'FLUTTER')),
    CONSTRAINT CK_DSO_SERVICE_DEPLOY_TARGET CHECK (DEPLOY_TARGET IN ('VM', 'OPENSHIFT')),
    CONSTRAINT CK_DSO_SERVICE_FLAGS CHECK (BUILD_TOOL_AUTO_SETUP IN (0, 1) AND DAST_ENABLED IN (0, 1)
        AND GOLDEN_FIX_ENABLED IN (0, 1) AND METRICS_ENABLED IN (0, 1)),
    CONSTRAINT CK_DSO_SERVICE_DAST CHECK (DAST_ENABLED = 0 OR DAST_TARGET_URL IS NOT NULL)
);

CREATE TABLE DSO_PIPELINE (
    ID                          NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    SERVICE_ID                  NUMBER(19)      NOT NULL,
    PIPELINE_TYPE               VARCHAR2(20)    NOT NULL,
    AGENT_LABELS                VARCHAR2(1000)  NOT NULL,
    EXTENDED_PIPELINE_JOB       VARCHAR2(500),
    DESCRIPTION                 VARCHAR2(1000),
    CREATED_AT                  TIMESTAMP       NOT NULL,
    UPDATED_AT                  TIMESTAMP       NOT NULL,
    VERSION                     NUMBER(10)      DEFAULT 0 NOT NULL,
    CONSTRAINT PK_DSO_PIPELINE PRIMARY KEY (ID),
    CONSTRAINT FK_DSO_PIPELINE_SERVICE FOREIGN KEY (SERVICE_ID) REFERENCES DSO_SERVICE (ID) ON DELETE CASCADE,
    CONSTRAINT UK_DSO_PIPELINE_TYPE UNIQUE (SERVICE_ID, PIPELINE_TYPE),
    CONSTRAINT CK_DSO_PIPELINE_TYPE CHECK (PIPELINE_TYPE IN ('FULL', 'SECURITY', 'EXTENDED', 'SAST'))
);

-- One row per key ever issued; a pipeline has at most one ACTIVE key, enforced by the application
-- under a row lock on DSO_PIPELINE. Revoked keys are kept as the audit trail.
CREATE TABLE DSO_PIPELINE_KEY (
    ID                          NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    PIPELINE_ID                 NUMBER(19)      NOT NULL,
    KEY_VALUE                   VARCHAR2(36)    NOT NULL,
    STATUS                      VARCHAR2(20)    NOT NULL,
    ISSUED_AT                   TIMESTAMP       NOT NULL,
    REVOKED_AT                  TIMESTAMP,
    REVOKE_REASON               VARCHAR2(500),
    LAST_USED_AT                TIMESTAMP,
    CONSTRAINT PK_DSO_PIPELINE_KEY PRIMARY KEY (ID),
    CONSTRAINT FK_DSO_PIPELINE_KEY_PIPELINE FOREIGN KEY (PIPELINE_ID) REFERENCES DSO_PIPELINE (ID) ON DELETE CASCADE,
    CONSTRAINT UK_DSO_PIPELINE_KEY_VALUE UNIQUE (KEY_VALUE),
    CONSTRAINT CK_DSO_PIPELINE_KEY_STATUS CHECK (
        (STATUS = 'ACTIVE' AND REVOKED_AT IS NULL) OR (STATUS = 'REVOKED' AND REVOKED_AT IS NOT NULL))
);

CREATE INDEX IX_DSO_PIPELINE_KEY_PIPELINE ON DSO_PIPELINE_KEY (PIPELINE_ID, STATUS);
